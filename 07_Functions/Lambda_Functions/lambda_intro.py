# Introduction to Lambda Functions in Python
# Syntax: lambda arguments : expression

# Lambda for addition of two numbers
add_num = lambda num_1, num_2: num_1 + num_2
print("Sum:", add_num(2, 3))

# Lambda for square of a number
num_square = lambda num_1: num_1 ** 2
print("Square:", num_square(5))

